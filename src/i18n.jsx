const Ctx = createContext(null);
const interpolate = (s, vars) => s.replace(/\{(\w+)\}/g, (_, k) => (vars && vars[k] !== undefined ? vars[k] : `{${k}}`));
const nf = new Intl.NumberFormat('en-IN');

function initialLang() {
  try {
    const saved = localStorage.getItem(STORAGE_KEY);
    if (saved === 'ne' || saved === 'en') return saved;
  } catch { /* storage unavailable */ }
  return 'ne';
}

export function LangProvider({ children }) {
  const [lang, setLang] = useState(initialLang);

  useEffect(() => {
    try { localStorage.setItem(STORAGE_KEY, lang); } catch { /* ignore */ }
    document.documentElement.lang = lang;
    document.title = lang === 'ne' ? 'लंगुर बुर्जा — नेपाली पासाको खेल' : 'Langur Burja — Nepali dice game';
  }, [lang]);

  const value = useMemo(() => {
    const other = lang === 'ne' ? 'en' : 'ne';
    const make = (l) => (key, vars) => interpolate(DICT[l][key] ?? DICT.en[key] ?? key, vars);
    const t = make(lang);
    return {
      lang,
      otherLang: other,
      setLang,
      toggle: () => setLang(other),
      t,
      alt: make(other),                                   // same string in the other language (shown as a subtitle)
      rs: (n) => `${lang === 'ne' ? 'रु' : 'Rs'} ${nf.format(n)}`,
      faceName: (key) => FACE_BY_KEY[key][lang === 'ne' ? 'nepali' : 'english'],
      faceAlt: (key) => FACE_BY_KEY[key][lang === 'ne' ? 'english' : 'nepali'],
      // Server / connection errors arrive as { code, msg }: translate by code, fall back to the English msg.
      te: (err) => (err ? (DICT[lang][`err.${err.code}`] ?? err.msg ?? '') : ''),
    };
  }, [lang]);

  return <Ctx.Provider value={value}>{children}</Ctx.Provider>;
}

export const useT = () => useContext(Ctx);
